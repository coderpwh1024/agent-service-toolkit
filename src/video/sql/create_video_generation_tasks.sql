CREATE TABLE IF NOT EXISTS video_generation_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    request_hash VARCHAR(64) NOT NULL,
    request_payload JSONB NOT NULL,
    task_id VARCHAR(128),
    status VARCHAR(32) NOT NULL DEFAULT 'SUBMITTING',
    storage_status VARCHAR(16) NOT NULL DEFAULT 'NOT_READY',
    aliyun_video_url TEXT,
    qiniu_video_url TEXT,
    qiniu_object_key TEXT,
    provider_request_id TEXT,
    error_code TEXT,
    next_poll_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_by BIGINT NOT NULL,
    update_by BIGINT NOT NULL,
    create_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_delete SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_video_generation_tasks PRIMARY KEY (id),
    CONSTRAINT ck_video_generation_tasks_user_id CHECK (user_id > 0),
    CONSTRAINT ck_video_generation_tasks_is_delete CHECK (is_delete IN (0, 1)),
    CONSTRAINT ck_video_generation_tasks_status CHECK (status IN (
        'SUBMITTING', 'SUBMISSION_UNKNOWN', 'PENDING', 'RUNNING',
        'SUCCEEDED', 'FAILED', 'CANCELED', 'UNKNOWN'
    )),
    CONSTRAINT ck_video_generation_tasks_storage_status CHECK (
        storage_status IN ('NOT_READY', 'PENDING', 'STORED', 'FAILED')
    ),
    CONSTRAINT ck_video_generation_tasks_stored CHECK (
        storage_status <> 'STORED' OR
        (status = 'SUCCEEDED' AND qiniu_video_url IS NOT NULL AND qiniu_object_key IS NOT NULL)
    )
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_video_generation_tasks_user_id_idempotency_key
    ON video_generation_tasks (user_id, idempotency_key) WHERE is_delete = 0;
CREATE UNIQUE INDEX IF NOT EXISTS uk_video_generation_tasks_task_id
    ON video_generation_tasks (task_id) WHERE task_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_video_generation_tasks_next_poll_time_id
    ON video_generation_tasks (next_poll_time, id)
    WHERE is_delete = 0 AND (
        status IN ('SUBMITTING', 'PENDING', 'RUNNING') OR
        (status = 'SUCCEEDED' AND storage_status <> 'STORED')
    );

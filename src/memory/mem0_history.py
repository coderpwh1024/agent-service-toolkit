"""PostgreSQL adapter for Mem0's history and bounded extraction context."""

from typing import Any

from psycopg.types.json import Jsonb
from psycopg_pool import ConnectionPool


class PostgresHistory:
    def __init__(self, pool: ConnectionPool, collection: str, actor_id: int) -> None:
        self.pool = pool
        self.collection = collection
        self.actor_id = actor_id

    def setup(self) -> None:
        with self.pool.connection() as conn:
            conn.execute("""
                CREATE TABLE IF NOT EXISTS mem0_records (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
                    collection_name TEXT NOT NULL,
                    kind TEXT NOT NULL,
                    scope TEXT NOT NULL,
                    payload JSONB NOT NULL,
                    create_by BIGINT NOT NULL,
                    update_by BIGINT NOT NULL,
                    create_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    update_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    is_delete SMALLINT NOT NULL DEFAULT 0,
                    CONSTRAINT pk_mem0_records PRIMARY KEY (id),
                    CONSTRAINT ck_mem0_records_kind CHECK (kind IN ('history', 'context')),
                    CONSTRAINT ck_mem0_records_is_delete CHECK (is_delete IN (0, 1))
                )
            """)
            conn.execute("""
                CREATE INDEX IF NOT EXISTS idx_mem0_records_collection_kind_scope
                ON mem0_records (collection_name, kind, scope, id) WHERE is_delete = 0
            """)
            conn.execute("""
                COMMENT ON TABLE mem0_records IS
                'Mem0 memory change history and extraction context; contains private user text'
            """)
            conn.execute("""
                COMMENT ON COLUMN mem0_records.scope IS
                'Memory UUID for history, escaped user/agent scope for extraction context'
            """)
            conn.execute("""
                COMMENT ON COLUMN mem0_records.payload IS
                'Mem0 history event or user message, never an application instruction'
            """)

    def _insert(self, conn: Any, kind: str, scope: str, payload: dict[str, Any]) -> None:
        conn.execute(
            """INSERT INTO mem0_records
               (collection_name, kind, scope, payload, create_by, update_by)
               VALUES (%s, %s, %s, %s, %s, %s)""",
            (self.collection, kind, scope, Jsonb(payload), self.actor_id, self.actor_id),
        )

    def add_history(
        self,
        memory_id: str,
        old_memory: str | None,
        new_memory: str | None,
        event: str,
        **details: Any,
    ) -> None:
        self.batch_add_history(
            [
                dict(
                    memory_id=memory_id,
                    old_memory=old_memory,
                    new_memory=new_memory,
                    event=event,
                    **details,
                )
            ]
        )

    def batch_add_history(self, records: list[dict[str, Any]]) -> None:
        with self.pool.connection() as conn:
            for record in records:
                self._insert(conn, "history", record["memory_id"], record)

    def get_history(self, memory_id: str) -> list[dict[str, Any]]:
        with self.pool.connection() as conn:
            rows = conn.execute(
                """SELECT id, payload FROM mem0_records
                   WHERE collection_name = %s AND kind = 'history' AND scope = %s
                   AND is_delete = 0 ORDER BY id""",
                (self.collection, memory_id),
            ).fetchall()
        return [dict(payload, id=str(record_id)) for record_id, payload in rows]

    def save_messages(self, messages: list[dict[str, Any]], session_scope: str) -> None:
        with self.pool.connection() as conn:
            for message in messages:
                self._insert(conn, "context", session_scope, message)
            conn.execute(
                """UPDATE mem0_records SET is_delete = 1, update_by = %s,
                   update_time = CURRENT_TIMESTAMP
                   WHERE collection_name = %s AND kind = 'context' AND scope = %s
                   AND is_delete = 0 AND id NOT IN (
                       SELECT id FROM mem0_records
                       WHERE collection_name = %s AND kind = 'context' AND scope = %s
                       AND is_delete = 0 ORDER BY id DESC LIMIT 10
                   )""",
                (self.actor_id, self.collection, session_scope, self.collection, session_scope),
            )

    def get_last_messages(self, session_scope: str, limit: int = 10) -> list[dict[str, Any]]:
        with self.pool.connection() as conn:
            rows = conn.execute(
                """SELECT payload FROM (
                       SELECT id, payload FROM mem0_records
                       WHERE collection_name = %s AND kind = 'context' AND scope = %s
                       AND is_delete = 0 ORDER BY id DESC LIMIT %s
                   ) AS recent ORDER BY id""",
                (self.collection, session_scope, limit),
            ).fetchall()
        return [row[0] for row in rows]

    def reset(self) -> None:
        raise RuntimeError(
            "Bulk memory reset requires an explicit PostgreSQL maintenance procedure"
        )

    def close(self) -> None:
        """The service lifecycle owns the shared pool."""

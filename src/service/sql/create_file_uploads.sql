CREATE TABLE IF NOT EXISTS file_uploads (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id BIGINT NOT NULL,
    url TEXT NOT NULL,
    bucket_name TEXT NOT NULL,
    object_key VARCHAR(128) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    content_type VARCHAR(127) NOT NULL,
    size_bytes BIGINT NOT NULL,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    create_by BIGINT NOT NULL,
    update_by BIGINT NOT NULL,
    create_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_delete SMALLINT NOT NULL DEFAULT 0,
    CONSTRAINT pk_file_uploads PRIMARY KEY (id),
    CONSTRAINT uk_file_uploads_object_key UNIQUE (object_key),
    CONSTRAINT ck_file_uploads_user_id CHECK (user_id > 0),
    CONSTRAINT ck_file_uploads_size_bytes CHECK (size_bytes > 0),
    CONSTRAINT ck_file_uploads_is_delete CHECK (is_delete IN (0, 1)),
    CONSTRAINT ck_file_uploads_metadata CHECK (
        length(trim(original_name)) > 0 AND length(trim(content_type)) > 0
        AND length(trim(bucket_name)) > 0 AND length(trim(object_key)) > 0
        AND url ~ '^https?://[^[:space:]]+$'
    )
);

COMMENT ON TABLE file_uploads IS '已确认上传到七牛的用户文件元数据；正文保存在对象存储，记录使用逻辑删除';
COMMENT ON COLUMN file_uploads.id IS '自增记录主键，与七牛对象键分离';
COMMENT ON COLUMN file_uploads.user_id IS '文件所属应用用户 ID；所有查询必须按当前用户隔离';
COMMENT ON COLUMN file_uploads.url IS '七牛公开域名下的完整持久 URL，不含签名或上传凭证';
COMMENT ON COLUMN file_uploads.bucket_name IS '上传时的七牛 Bucket，保留配置变更前的存储位置';
COMMENT ON COLUMN file_uploads.object_key IS '服务端生成的唯一对象键，逻辑删除后也不得复用';
COMMENT ON COLUMN file_uploads.original_name IS '去除路径后的原始文件名，最多 255 个字符，不用于构造对象键';
COMMENT ON COLUMN file_uploads.content_type IS '客户端声明的 MIME 类型，缺省为 application/octet-stream，不代表内容安全验证';
COMMENT ON COLUMN file_uploads.size_bytes IS '实际上传文件大小，单位字节，必须大于零';
COMMENT ON COLUMN file_uploads.uploaded_at IS '七牛确认上传后写入元数据的时间，与数据库审计时间语义分离';
COMMENT ON COLUMN file_uploads.create_by IS '创建记录的应用用户 ID，插入后不变';
COMMENT ON COLUMN file_uploads.update_by IS '最后实际修改记录的用户或服务账号 ID';
COMMENT ON COLUMN file_uploads.create_time IS '数据库记录创建时间';
COMMENT ON COLUMN file_uploads.update_time IS '数据库记录最后实际修改时间，更新时须显式刷新';
COMMENT ON COLUMN file_uploads.is_delete IS '逻辑删除标记：0 有效，1 已删除；默认查询只返回 0';
